#!/bin/bash
# Generate CHANGELOG.md from the repository's merge history.
# The merge commits are the verifiable source of truth: every phase is a PR;
# each row is reproducible with `git log --merges --oneline`.
# Usage: docs/gen_changelog.sh [> CHANGELOG.md]

cd "$(git rev-parse --show-toplevel)"

echo "# CHANGELOG"
echo
echo "One row per merged PR, generated by \`docs/gen_changelog.sh\`;"
echo "verify with \`git log --merges --oneline\`."
echo

echo "## Phases (merged PRs)"
echo
echo "| PR | Phase (branch) |"
echo "|---|---|"
git log --merges --reverse --format="%s" origin/main 2>/dev/null | while IFS= read -r subject; do
    pr=$(echo "$subject" | grep -oE '#[0-9]+' | head -1)
    if [ -n "$pr" ]; then
        phase=$(echo "$subject" | sed -E "s/^Merge pull request #[0-9]+ from [^:]*[\/:]//")
        echo "| $pr | $(echo "$phase" | xargs) |"
    else
        echo "| - | $(echo "$subject" | xargs) |"
    fi
done

echo
echo "## Key decisions"
echo
echo "- ADR-0001 - invocation model: one process per request in its own working directory."
echo "- ADR-0002 - the libmysqlclient bridge replaced the ODBC / embedded-SQL auth stack."
echo "- ADR-0003 - idempotent transfers via an idempotency key doubling as the transaction reference."
echo
echo "## Standards"
echo
echo "- Workflow, language, business-logic boundary, shell-safety: \`AGENTS.md\`."
echo "- Review rules (mechanical + judgement): \`CODING_STANDARDS.md\`."
echo "- Per-module current state (as-built + gaps): \`SPEC-*.md\`; snapshot: \`docs/STATUS.md\`."
