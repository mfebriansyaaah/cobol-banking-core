// Train-profile curation (Phase 1).
//
// The `train` export is a training corpus, not a runnable tree. It must not
// carry modules the repository itself marks as non-recommended for training
// (`manifest/module_quality.json`), nor the generated route boilerplate that
// duplicates `middleware/spec/routes.yaml`.
//
// Usage:
//   node scripts/train_profile.mjs --list
//   node scripts/train_profile.mjs --check <export-dir>
//
// `--list` prints one repo-relative path per line; export_dataset.sh removes
// each path from the archive. `--check` fails closed if a forbidden module or
// generated route survives the export.
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const GENERATED_ROUTE_HEADER = 'Generated by scripts/build_routes.mjs';
// One generated route file stays as a concrete example of the generator's
// output; the spec remains the source of truth. `card.js` exercises public
// and token-bound routes plus money actions.
export const ROUTE_EXEMPLARS = new Set(['card.js']);

function readJson(rootDir, rel) {
  return JSON.parse(readFileSync(path.join(rootDir, rel), 'utf8'));
}

export function loadQuality(rootDir = ROOT) {
  const data = readJson(rootDir, 'manifest/module_quality.json');
  return data.modules || [];
}

export function nonRecommendedModules(rootDir = ROOT) {
  return loadQuality(rootDir).filter((m) => !m.recommendedForTraining);
}

function dispatchTable(rootDir) {
  const data = readJson(rootDir, 'manifest/modules.json');
  return [...(data.dispatch || [])].sort((a, b) => b.prefixLen - a.prefixLen || b.prefix.length - a.prefix.length);
}

function programForAction(action, dispatch) {
  for (const entry of dispatch) {
    if (action.startsWith(entry.prefix)) return entry.program;
  }
  return null;
}

/** Map each COBOL table-case file to the set of modules its actions dispatch to. */
export function caseFilesByModule(rootDir = ROOT) {
  const dir = path.join(rootDir, 'tests', 'cobol', 'cases');
  if (!existsSync(dir)) return new Map();
  const dispatch = dispatchTable(rootDir);
  const out = new Map();
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith('.cases'))
    .sort()) {
    const programs = new Set();
    for (const line of readFileSync(path.join(dir, file), 'utf8').split('\n')) {
      const text = line.trim();
      if (!text || text.startsWith('#')) continue;
      const parts = text.split('@@');
      if (parts.length < 3) continue;
      const action = parts[2].split('|')[0].trim();
      const program = programForAction(action, dispatch);
      if (program) programs.add(program);
    }
    out.set(`tests/cobol/cases/${file}`, programs);
  }
  return out;
}

function generatedRouteFiles(rootDir) {
  const dir = path.join(rootDir, 'middleware', 'src', 'routes');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.js'))
    .filter((f) => {
      const first = readFileSync(path.join(dir, f), 'utf8').split('\n', 1)[0];
      return first.includes(GENERATED_ROUTE_HEADER);
    })
    .map((f) => `middleware/src/routes/${f}`);
}

/** Repo-relative paths that must not appear in the train export. */
export function pathsToDrop(rootDir = ROOT) {
  const nonRecommended = nonRecommendedModules(rootDir);
  const excluded = new Set(nonRecommended.map((m) => m.module));
  const out = new Set();

  for (const m of nonRecommended) {
    out.add(`cobol/src/${m.module}.cob`);
    if (m.dbSuite) out.add(m.dbSuite);
  }

  for (const [file, programs] of caseFilesByModule(rootDir)) {
    if (programs.size > 0 && [...programs].every((p) => excluded.has(p))) out.add(file);
  }

  for (const file of generatedRouteFiles(rootDir)) {
    if (!ROUTE_EXEMPLARS.has(path.basename(file))) out.add(file);
  }
  // The barrel imports every generated route; it is meaningless without them.
  if (existsSync(path.join(rootDir, 'middleware', 'src', 'routes', 'index.js'))) {
    out.add('middleware/src/routes/index.js');
  }

  // Generated snapshots are excluded by export_dataset.sh for both source and
  // train. Keep the list here so the check is independent of shell history.
  out.add('database/schema_full.sql');
  out.add('database/schema_v2.sql');
  out.add('database/schema_v2.sql.gz');
  out.add('docs/openapi.yaml');
  out.add('contracts/actions.yaml');
  out.add('manifest/actions.json');
  out.add('tests/contracts/route_field_order.json');
  out.add('docs/DATA_DICTIONARY.md');
  out.add('docs/STATUS.md');
  out.add('docs/MODULE_INDEX.md');
  out.add('docs/COMPLEXITY_BASELINE.md');

  return [...out].sort();
}

function routeFilesInExport(outDir) {
  const dir = path.join(outDir, 'middleware', 'src', 'routes');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.js'))
    .map((f) => ({ name: f, text: readFileSync(path.join(dir, f), 'utf8').split('\n', 1)[0] }))
    .filter((f) => f.text.includes(GENERATED_ROUTE_HEADER))
    .map((f) => f.name);
}

/** Fail closed when an export still carries a forbidden module or generated route. */
export function checkExport(outDir) {
  const errors = [];
  for (const m of nonRecommendedModules(ROOT)) {
    if (existsSync(path.join(outDir, 'cobol', 'src', `${m.module}.cob`))) {
      errors.push(`non-recommended module survived: ${m.module}`);
    }
  }

  for (const file of routeFilesInExport(outDir)) {
    if (!ROUTE_EXEMPLARS.has(file)) errors.push(`generated route survived: middleware/src/routes/${file}`);
  }
  if (!existsSync(path.join(outDir, 'middleware', 'spec', 'routes.yaml'))) {
    errors.push('route spec missing: middleware/spec/routes.yaml');
  }
  if (existsSync(path.join(outDir, 'middleware', 'src', 'routes', 'index.js'))) {
    errors.push('generated route barrel survived: middleware/src/routes/index.js');
  }
  if (existsSync(path.join(outDir, 'database', 'migrations', 'archive'))) {
    errors.push('migration archive survived in train export');
  }
  for (const rel of ['database/schema_full.sql', 'database/schema_v2.sql', 'database/schema_v2.sql.gz']) {
    if (existsSync(path.join(outDir, rel))) errors.push(`generated schema snapshot survived: ${rel}`);
  }

  const infoPath = path.join(outDir, 'DATASET_INFO.json');
  if (existsSync(infoPath)) {
    try {
      const info = JSON.parse(readFileSync(infoPath, 'utf8'));
      if (info.profile !== 'train') errors.push(`DATASET_INFO.json profile is ${info.profile}, expected train`);
    } catch {
      errors.push('DATASET_INFO.json is not valid JSON');
    }
  }

  if (errors.length > 0) {
    for (const err of errors) console.error(`FAIL: ${err}`);
    return 1;
  }
  console.log(`OK: train profile is curated (${nonRecommendedModules(ROOT).length} non-recommended modules excluded)`);
  return 0;
}

function main(argv) {
  if (argv[0] === '--list' && argv.length === 1) {
    for (const rel of pathsToDrop(ROOT)) console.log(rel);
    return 0;
  }
  if (argv[0] === '--check' && argv.length === 2) {
    return checkExport(path.resolve(argv[1]));
  }
  console.error('usage: node scripts/train_profile.mjs --list | --check <export-dir>');
  return 2;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
