// Assertion-count gate: the numbers in tests/baseline_counts.txt are
// load-bearing. Removing an assertion (or a whole suite's assertions) without
// updating the baseline fails the run instead of silently shrinking coverage.
//
// Two data sources:
//   runtime (default): tests report rows from <report-dir>/report.tsv
//     (written by tests/lib/report.sh) plus gateway JUnit XMLs
//     (junit-*.xml) in the same directory.
//   static (--static): counts assert_match lines per tests/db/*.sh and @@
//     case lines, without running anything. Used by the probes harness and
//     for fast local checks. Exact counts hold for every suite except the
//     documented LOOP_GENERATED set (loop-generated assertions: 19 lines
//     execute 76 times in db_schema_tests); those are checked loosely here
//     and exactly at runtime.
//
// Usage:
//   node scripts/check_test_counts.mjs [--report-dir DIR] [--strict]
//   node scripts/check_test_counts.mjs --static [ROOT] [--write]
//   node scripts/check_test_counts.mjs --report-dir DIR --write
// Exit: 0 ok, 1 mismatch, 2 usage error.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
let reportDir = 'artifacts';
let root = '.';
let staticMode = false;
let write = false;
let strict = false;
for (let i = 0; i < args.length; i += 1) {
  const a = args[i];
  if (a === '--report-dir') reportDir = args[i + 1] ?? reportDir, i += 1;
  else if (a === '--root') root = args[i + 1] ?? root, i += 1;
  else if (a === '--static') staticMode = true;
  else if (a === '--write') write = true;
  else if (a === '--strict') strict = true;
  else if (a === '--help' || a === '-h') {
    console.log('usage:');
    console.log('  check_test_counts.mjs [--root DIR] [--report-dir DIR] [--strict]');
    console.log('  check_test_counts.mjs --static [--root DIR] [--write]');
    process.exit(0);
  } else if (a.startsWith('--')) {
    console.error(`unknown argument: ${a}`);
    process.exit(2);
  } else if (staticMode) root = a;
  else {
    console.error(`unexpected argument: ${a} (see --help)`);
    process.exit(2);
  }
}
reportDir = path.resolve(reportDir);
root = path.resolve(root);

// Suites whose assertions are generated by shell loops: one assert_match line
// executes many times, so a static line count can never equal the runtime
// total. Static mode only requires these to exist and be non-empty; the exact
// count is enforced at runtime.
const LOOP_GENERATED = new Set(['db_schema_tests']);
// Report rows that are recorded but intentionally not count-gated. `smoke` is
// a 1-assertion liveness check; its failure already fails the run.
const KNOWN_UNTRACKED = new Set(['smoke']);

const baselinePath = path.join(root, 'tests', 'baseline_counts.txt');

function loadBaseline() {
  if (!existsSync(baselinePath)) {
    console.error(`FAIL: missing ${baselinePath}`);
    process.exit(2);
  }
  const raw = readFileSync(baselinePath, 'utf8').split('\n');
  const values = new Map();
  const order = [];
  for (const line of raw) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq < 0) continue;
    values.set(line.slice(0, eq).trim(), Number(line.slice(eq + 1).trim()));
  }
  for (const line of raw) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq >= 0) order.push(line.slice(0, eq).trim());
  }
  return { raw, values, order };
}

function keyForDbFile(file) {
  if (file === 'schema_tests.sh') return 'db_schema_tests';
  const m = file.match(/^(.+)_db_tests\.sh$/);
  return m ? `db_${m[1]}_tests` : null;
}

// ---- runtime data (report.tsv + JUnit) ----
function loadRuntime() {
  const tsvPath = path.join(reportDir, 'report.tsv');
  const rows = new Map(); // key -> totals[]
  let missing = null;
  if (!existsSync(tsvPath)) {
    missing = `missing ${tsvPath}`;
  } else {
    const lines = readFileSync(tsvPath, 'utf8').split('\n').filter((l) => l.trim() !== '');
    if (!lines.length || lines[0].split('\t').join(',') !== 'suite,status,pass,fail,total,duration_ms,shard') {
      return { rows, gateway: null, missing: `${tsvPath} has an unexpected header` };
    }
    for (const line of lines.slice(1)) {
      const cols = line.split('\t');
      if (cols.length !== 7) return { rows, gateway: null, missing: `malformed row: ${line}` };
      const [suite, status, pass, fail, total] = cols;
      const nums = [pass, fail, total].map((v) => Number.parseInt(v, 10));
      if (nums.some((n) => !Number.isFinite(n) || n < 0)) {
        return { rows, gateway: null, missing: `non-numeric counters in row: ${line}` };
      }
      let key = null;
      if (suite === 'table_runner.sh') key = 'cobol_table_tests';
      else if (suite === 'smoke' || KNOWN_UNTRACKED.has(suite)) continue;
      else if (suite === 'schema_tests.sh') key = 'db_schema_tests';
      else {
        const m = suite.match(/^(.+)_db_tests\.sh$/);
        key = m ? `db_${m[1]}_tests` : suite;
      }
      if (!rows.has(key)) rows.set(key, []);
      rows.get(key).push({ total: nums[2], status, file: suite });
    }
  }
  // gateway_tests from JUnit XMLs (Node junit: bare testcases; tap converter: testsuite attrs).
  let gateway = null;
  if (existsSync(reportDir)) {
    let tests = 0;
    let files = 0;
    const walk = (dir) => {
      for (const e of readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, e.name);
        if (e.isDirectory()) walk(p);
        else if (e.name.endsWith('.xml')) {
          const src = readFileSync(p, 'utf8');
          if (!src.includes('<testsuite') && !src.includes('<testcase')) continue;
          files += 1;
          const m = src.match(/<testsuite[^>]*\stests="(\d+)"/);
          if (m) tests += Number(m[1]);
          else tests += (src.match(/<testcase[\s>]/g) || []).length;
        }
      }
    };
    try {
      walk(reportDir);
    } catch {
      return { rows, gateway: null, missing: `cannot scan ${reportDir}` };
    }
    if (files > 0) gateway = tests;
  }
  return { rows, gateway, missing };
}

// ---- static data (file contents, no execution) ----
function loadStatic() {
  const rows = new Map();
  const dbDir = path.join(root, 'tests', 'db');
  if (!existsSync(dbDir)) return { rows, gateway: 'skip', missing: `missing ${dbDir}` };
  for (const f of readdirSync(dbDir).filter((x) => x.endsWith('.sh')).sort()) {
    const key = keyForDbFile(f);
    if (!key) continue;
    const src = readFileSync(path.join(dbDir, f), 'utf8');
    const n = src.split('\n').filter((l) => /(^|[\s;])assert_match[\s(]/.test(l)).length;
    if (!rows.has(key)) rows.set(key, []);
    rows.get(key).push({ total: n, status: n > 0 ? 'pass' : 'missing', file: f });
  }
  // Table cases: one assertion per non-comment line containing @@.
  const casesDir = path.join(root, 'tests', 'cobol', 'cases');
  let cases = 0;
  if (existsSync(casesDir)) {
    for (const f of readdirSync(casesDir).filter((x) => x.endsWith('.cases'))) {
      for (const line of readFileSync(path.join(casesDir, f), 'utf8').split('\n')) {
        const t = line.trim();
        if (!t || t.startsWith('#')) continue;
        if (t.includes('@@')) cases += 1;
      }
    }
  }
  rows.set('cobol_table_tests', [{ total: cases, status: cases > 0 ? 'pass' : 'missing', file: 'tests/cobol/cases/*.cases' }]);
  // Gateway tests are generated dynamically (contract.test.js emits one test
  // per route file); no static count exists. Runtime mode covers them.
  return { rows, gateway: 'skip', missing: null };
}

const { values: baseline, order, raw } = loadBaseline();
const data = staticMode ? loadStatic() : loadRuntime();

let failed = false;
const notes = [];

if (data.missing && !write) {
  console.error(`FAIL: ${data.missing}`);
  process.exit(1);
}

// 1. unlisted: data keys with no baseline entry.
const unlisted = [...data.rows.keys()].filter((k) => !baseline.has(k));
if (unlisted.length) {
  failed = true;
  console.error('SUITES WITH NO baseline_counts.txt ENTRY (counts would grow untracked):');
  for (const k of unlisted.sort()) console.error(`  ${k}`);
  console.error('  Add a line, or extend KNOWN_UNTRACKED in scripts/check_test_counts.mjs with a reason.');
}

// 2/3/4. missing keys, drift, zero totals.
const missingKeys = [];
const drifts = [];
const zeroes = [];
for (const key of order) {
  if (key === 'gateway_tests') continue; // handled below (runtime) or skipped (static)
  const expected = baseline.get(key);
  const got = data.rows.get(key);
  if (!got || !got.length) {
    missingKeys.push(key);
    continue;
  }
  const distinct = [...new Set(got.map((r) => r.total))];
  if (distinct.length > 1) {
    failed = true;
    console.error(`FAIL: ${key} has inconsistent totals across rows: ${distinct.join(', ')}`);
    console.error('  Regenerate the report from a single fresh run (do not append runs).');
    continue;
  }
  const actual = distinct[0];
  if (staticMode && LOOP_GENERATED.has(key)) {
    if (actual === 0) {
      failed = true;
      zeroes.push(`${key} (no assert_match lines at all)`);
    } else {
      notes.push(`${key}: static=${actual} (loop-generated; exact total ${expected} enforced at runtime)`);
    }
    continue;
  }
  if (actual === 0) {
    failed = true;
    zeroes.push(`${key} (baseline ${expected}, actual 0)`);
    continue;
  }
  if (actual !== expected) {
    failed = true;
    drifts.push(`${key}: baseline=${expected} actual=${actual}`);
  }
}
if (missingKeys.length) {
  const lines = missingKeys.map((k) => `  ${k} (baseline ${baseline.get(k)})`);
  if (strict) {
    failed = true;
    console.error('BASELINE KEYS WITH NO DATA IN THIS RUN (did the suite run?):');
    for (const l of lines) console.error(l);
  } else if (write) {
    for (const k of missingKeys) notes.push(`${k}: kept baseline ${baseline.get(k)} (not in this run)`);
  } else {
    console.error('WARN: baseline keys with no data in this run (use --strict to enforce):');
    for (const l of lines) console.error(l);
  }
}
if (drifts.length) {
  failed = true;
  console.error('COUNT DRIFT (baseline vs actual):');
  for (const d of drifts) console.error(`  ${d}`);
  console.error('  If the change is intentional, regenerate with --write and review the diff.');
}
if (zeroes.length) {
  failed = true;
  console.error('ZERO-ASSERTION SUITES:');
  for (const z of zeroes) console.error(`  ${z}`);
}

// gateway_tests.
if (data.gateway === 'skip') {
  notes.push('gateway_tests: skipped in static mode (dynamic test generation; enforced at runtime)');
} else if (data.gateway === null) {
  if (baseline.has('gateway_tests')) {
    if (write) {
      notes.push(`gateway_tests: no JUnit XML in ${reportDir}; keeping baseline ${baseline.get('gateway_tests')}`);
    } else if (strict) {
      failed = true;
      console.error('BASELINE KEYS WITH NO DATA IN THIS RUN (did the suite run?):');
      console.error(`  gateway_tests (baseline ${baseline.get('gateway_tests')}; no JUnit XML in ${reportDir})`);
    } else {
      console.error('WARN: gateway_tests has no JUnit XML in this run (use --strict to enforce)');
    }
  }
} else if (baseline.has('gateway_tests')) {
  if (data.gateway !== baseline.get('gateway_tests')) {
    failed = true;
    console.error('COUNT DRIFT (baseline vs actual):');
    console.error(`  gateway_tests: baseline=${baseline.get('gateway_tests')} actual=${data.gateway}`);
  }
} else {
  failed = true;
  console.error('SUITES WITH NO baseline_counts.txt ENTRY (counts would grow untracked):');
  console.error('  gateway_tests');
}

// --write: update baseline from data, preserving structure.
if (write) {
  if (zeroes.length) {
    console.error('FAIL: refusing --write with zero-assertion suites (fix the suite first):');
    for (const z of zeroes) console.error(`  ${z}`);
    process.exit(1);
  }
  if (failed && drifts.length === 0 && missingKeys.length === 0 && unlisted.length === 0 && zeroes.length === 0) {
    // Only notes (loop/static skips): nothing to write.
  }
  const updates = new Map();
  for (const [key, rowsArr] of data.rows) {
    if (!baseline.has(key)) {
      // New key: take the value when unambiguous.
      const distinct = [...new Set(rowsArr.map((r) => r.total))];
      if (distinct.length > 1) {
        console.error(`FAIL: refusing --write for ${key}: inconsistent totals ${distinct.join(', ')}`);
        process.exit(1);
      }
      if (staticMode && LOOP_GENERATED.has(key)) continue;
      updates.set(key, { value: distinct[0], isNew: true });
      continue;
    }
    if (staticMode && LOOP_GENERATED.has(key)) {
      notes.push(`${key}: kept baseline ${baseline.get(key)} (loop-generated; not writable statically)`);
      continue;
    }
    const distinct = [...new Set(rowsArr.map((r) => r.total))];
    if (distinct.length > 1) {
      console.error(`FAIL: refusing --write for ${key}: inconsistent totals ${distinct.join(', ')}`);
      process.exit(1);
    }
    if (distinct[0] !== baseline.get(key)) updates.set(key, { value: distinct[0], isNew: false });
  }
  if (data.gateway !== null && data.gateway !== 'skip' && baseline.has('gateway_tests') && data.gateway !== baseline.get('gateway_tests')) {
    updates.set('gateway_tests', { value: data.gateway, isNew: false });
  }
  if (!updates.size) {
    console.log('baseline already matches; nothing to write');
  } else {
    const out = [];
    const seen = new Set();
    for (const line of raw) {
      const t = line.trim();
      if (!t || t.startsWith('#') || !line.includes('=')) {
        out.push(line);
        continue;
      }
      const key = line.slice(0, line.indexOf('=')).trim();
      seen.add(key);
      if (updates.has(key)) out.push(`${key}=${updates.get(key).value}`);
      else out.push(line);
    }
    for (const [key, u] of updates) {
      if (!seen.has(key)) out.push(`${key}=${u.value}`);
    }
    writeFileSync(baselinePath, `${out.join('\n').replace(/\n+$/, '')}\n`);
    console.log(`wrote ${updates.size} baseline value(s):`);
    for (const [key, u] of updates) {
      console.log(`  ${key}: ${baseline.get(key) ?? '(new)'} -> ${u.value}`);
    }
  }
  for (const n of notes) console.log(`note: ${n}`);
  // Drifts and new keys are resolved by the write itself (zeroes and
  // inconsistent duplicates are refused above), so a completed write is green.
  process.exit(0);
}

for (const n of notes) console.log(`note: ${n}`);
if (failed) {
  console.error(`\nFAIL: assertion counts do not match ${baselinePath}`);
  process.exit(1);
}
const suiteCount = data.rows.size;
const totalAsserts = [...data.rows.values()].flat().reduce((a, r) => a + r.total, 0);
console.log(`OK: ${suiteCount} suite key(s), ${totalAsserts} assertion(s) match baseline_counts.txt`);
