// Unit tests for train-profile curation. No database, no build, no archive.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { ROOT, caseFilesByModule, checkExport, pathsToDrop } from '../train_profile.mjs';

test('train drop list follows module_quality, not a hardcoded clone list', () => {
  const drops = new Set(pathsToDrop(ROOT));
  const quality = JSON.parse(readFileSync(path.join(ROOT, 'manifest', 'module_quality.json'), 'utf8')).modules;
  const nonRecommended = quality.filter((m) => !m.recommendedForTraining);
  for (const m of nonRecommended) {
    assert.equal(m.linkageLevel, 'UTILITY', `only utility modules may be non-recommended (${m.module})`);
  }
  for (const m of quality.filter((x) => x.recommendedForTraining)) {
    assert.ok(!drops.has(`cobol/src/${m.module}.cob`), `${m.module} is recommended and stays`);
  }
  assert.ok(!drops.has('cobol/src/account_core.cob'), 'refactored account module stays');
  assert.ok(!drops.has('cobol/src/auth_core.cob'), 'ACTIVE core module stays');
  assert.ok(!drops.has('cobol/src/wallet_transfer_core.cob'), 'recommended transfer module stays');
});

test('generated routes are removed except one exemplar, and the spec stays out of the drop list', () => {
  const drops = new Set(pathsToDrop(ROOT));
  assert.ok(drops.has('middleware/src/routes/admin.js'));
  assert.ok(drops.has('middleware/src/routes/index.js'));
  assert.ok(!drops.has('middleware/src/routes/card.js'), 'card.js is the generated exemplar');
  assert.ok(!drops.has('middleware/spec/routes.yaml'), 'the route spec is the source of truth');
});

test('case files for recommended modules are kept', () => {
  const cases = caseFilesByModule(ROOT);
  assert.ok(cases.get('tests/cobol/cases/report.cases').has('report_core'));
  assert.ok(cases.get('tests/cobol/cases/auth_user.cases').has('auth_core'));
  assert.ok(cases.get('tests/cobol/cases/account.cases').has('account_core'));
  const drops = new Set(pathsToDrop(ROOT));
  assert.ok(!drops.has('tests/cobol/cases/report.cases'));
  assert.ok(!drops.has('tests/cobol/cases/account.cases'));
  assert.ok(!drops.has('tests/cobol/cases/auth_user.cases'));
});

function fixtureExport() {
  const dir = mkdtempSync(path.join(tmpdir(), 'train-export-'));
  mkdirSync(path.join(dir, 'middleware', 'spec'), { recursive: true });
  mkdirSync(path.join(dir, 'middleware', 'src', 'routes'), { recursive: true });
  writeFileSync(path.join(dir, 'middleware', 'spec', 'routes.yaml'), 'files: []\n');
  writeFileSync(path.join(dir, 'middleware', 'src', 'routes', 'card.js'), '// Generated by scripts/build_routes.mjs\n');
  writeFileSync(path.join(dir, 'DATASET_INFO.json'), `${JSON.stringify({ profile: 'train', fileCount: 1 })}\n`);
  return dir;
}

test('checkExport accepts a curated fixture and rejects a surviving generated route', () => {
  const dir = fixtureExport();
  try {
    assert.equal(checkExport(dir), 0);
    writeFileSync(
      path.join(dir, 'middleware', 'src', 'routes', 'admin.js'),
      '// Generated by scripts/build_routes.mjs\n',
    );
    assert.equal(checkExport(dir), 1);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('checkExport rejects a migration archive that survived', () => {
  const dir = fixtureExport();
  try {
    mkdirSync(path.join(dir, 'database', 'migrations', 'archive'), { recursive: true });
    writeFileSync(path.join(dir, 'database', 'migrations', 'archive', 'x.sql'), '');
    assert.equal(checkExport(dir), 1);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
