// Per-module quality manifest (audit P1-08): tier, linkage, disposition,
// clone signal, and coverage in one place so dataset consumers can
// filter/downweight weak modules without guessing.
// Usage:
//   node scripts/build_module_quality.mjs --write [--root DIR]
//   node scripts/build_module_quality.mjs --check [--root DIR]
// Exit: 0 ok, 1 drift on --check, 2 usage error.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
let mode = 'check';
let root = '.';
for (let i = 0; i < args.length; i += 1) {
  const a = args[i];
  if (a === '--write') mode = 'write';
  else if (a === '--check') mode = 'check';
  else if (a === '--root') {
    root = args[i + 1] ?? root;
    i += 1;
  } else if (!a.startsWith('--')) {
    root = a;
  } else {
    console.error(`unknown argument: ${a}`);
    process.exit(2);
  }
}
root = path.resolve(root);

const loadJson = (p) => JSON.parse(readFileSync(p, 'utf8'));

function parseCloneBaseline(p) {
  const out = new Map();
  if (!existsSync(p)) return out;
  for (const line of readFileSync(p, 'utf8').split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const m = t.match(/^(\S+).*sim=([0-9.]+)/);
    if (m) out.set(m[1].replace(/\.cob$/, ''), Number(m[2]));
  }
  return out;
}

function parseCoverageBaseline(p) {
  const out = new Map();
  if (!existsSync(p)) return out;
  for (const line of readFileSync(p, 'utf8').split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const m = t.match(/^(\S+)\s+([0-9.]+)/);
    if (m) out.set(m[1], Number(m[2]));
  }
  return out;
}

function parseFloorBacklog(p) {
  const out = new Set();
  if (!existsSync(p)) return out;
  for (const line of readFileSync(p, 'utf8').split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    out.add(t.split(/\s+/)[0]);
  }
  return out;
}

export function build(rootDir = root) {
  const domainStatus = loadJson(path.join(rootDir, 'manifest', 'domain_status.json'));
  const codeCandidates = loadJson(path.join(rootDir, 'manifest', 'code_candidates.json'));
  const kindByModule = new Map();
  for (const c of codeCandidates.candidates || []) {
    const kind = /^DUPLICATE/.test(c.reason || '') ? 'DUPLICATE' : 'UNLINKED';
    kindByModule.set(c.module, kind);
  }
  const cloneSim = parseCloneBaseline(path.join(rootDir, 'tests', 'clone_baseline.txt'));
  const coverage = parseCoverageBaseline(path.join(rootDir, 'tests', 'coverage_module_baseline.txt'));
  parseFloorBacklog(path.join(rootDir, 'tests', 'coverage_floor_backlog.txt'));

  const modules = [...(domainStatus.entries || [])]
    .sort((a, b) => a.module.localeCompare(b.module))
    .map((e) => {
      const base = e.module.endsWith('_core') ? e.module.slice(0, -5) : e.module;
      const dbPath = `tests/db/${base}_db_tests.sh`;
      const sim = cloneSim.has(e.module) ? cloneSim.get(e.module) : null;
      const cov = coverage.has(e.module) ? coverage.get(e.module) : null;
      return {
        module: e.module,
        tier: e.tier,
        linkageLevel: e.linkageLevel,
        domainStatus: e.status,
        candidateStatus: kindByModule.get(e.module) || null,
        cloneSimilarity: sim,
        coveragePercent: cov,
        coverageStatus: cov === null ? 'unmeasured' : cov >= 70 ? 'ok' : 'floor',
        routeFile: e.routeFile || null,
        dbSuite: existsSync(path.join(rootDir, dbPath)) ? dbPath : null,
        recommendedForTraining:
          (e.status === 'ACTIVE' || e.status === 'PILOT') && !(sim !== null && sim >= 0.9),
      };
    });
  return { generatedAt: new Date().toISOString(), modules };
}

export function renderMarkdown(quality) {
  const rows = quality.modules.map(
    (m) =>
      `| \`${m.module}\` | ${m.tier} | ${m.linkageLevel} | ${m.domainStatus} | ${m.candidateStatus || '—'} | ${m.cloneSimilarity ?? '—'} | ${m.coveragePercent ?? '—'} | ${m.coverageStatus} | ${m.recommendedForTraining ? 'yes' : 'no'} |`,
  );
  return `# Module Quality

> Generated by \`scripts/build_module_quality.mjs --write\`. Do not edit by
> hand. Per-module tier/linkage/disposition/clone/coverage for dataset
> filtering. See \`docs/DOMAIN_STATUS.md\` for dispositions and
> \`docs/COVERAGE.md\` for coverage scope.
> Recommended = ACTIVE/PILOT with no 0.9+ clone similarity.

| Module | Tier | Link | Status | Candidate | Clone sim | Coverage % | Coverage | Recommended |
| --- | ---: | --- | --- | --- | ---: | --- | --- | --- |
${rows.join('\n')}
`;
}

const quality = build(root);
const jsonOut = path.join(root, 'manifest', 'module_quality.json');
const mdOut = path.join(root, 'docs', 'MODULE_QUALITY.md');

if (mode === 'write') {
  writeFileSync(jsonOut, `${JSON.stringify(quality, null, 2)}\n`);
  writeFileSync(mdOut, renderMarkdown(quality));
  console.log(`Wrote manifest/module_quality.json + docs/MODULE_QUALITY.md (${quality.modules.length} modules)`);
} else {
  const fail = (msg) => {
    console.error(`FAIL: ${msg}`);
    process.exit(1);
  };
  if (!existsSync(jsonOut)) fail('manifest/module_quality.json missing; run scripts/build_module_quality.mjs --write');
  if (!existsSync(mdOut)) fail('docs/MODULE_QUALITY.md missing; run scripts/build_module_quality.mjs --write');
  const recorded = loadJson(jsonOut);
  if ((recorded.modules || []).length !== quality.modules.length) {
    fail(`module count drift (recorded ${(recorded.modules || []).length}, tree has ${quality.modules.length})`);
  }
  const byName = new Map((recorded.modules || []).map((m) => [m.module, m]));
  for (const m of quality.modules) {
    const r = byName.get(m.module);
    if (!r) fail(`module missing from manifest: ${m.module}`);
    for (const k of [
      'tier',
      'linkageLevel',
      'domainStatus',
      'candidateStatus',
      'cloneSimilarity',
      'coveragePercent',
      'coverageStatus',
      'routeFile',
      'dbSuite',
      'recommendedForTraining',
    ]) {
      if (JSON.stringify(r[k]) !== JSON.stringify(m[k])) {
        fail(`${m.module}: field ${k} drifted (recorded ${JSON.stringify(r[k])}, tree has ${JSON.stringify(m[k])})`);
      }
    }
  }
  const recordedMd = readFileSync(mdOut, 'utf8');
  if (recordedMd !== renderMarkdown(recorded)) fail('docs/MODULE_QUALITY.md drifted; run --write after review');
  console.log(`OK: ${quality.modules.length} modules`);
}
