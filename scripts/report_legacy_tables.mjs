// Legacy table report (audit P2-13, DBA-led): list every table in
// database/schema.sql with a code-reference signal. Report only — no DROP,
// no ownership change. DBA triages KEEP/DROP_CANDIDATE/DEFER afterwards.
// Usage:
//   node scripts/report_legacy_tables.mjs --write [--root DIR]
//   node scripts/report_legacy_tables.mjs --check [--root DIR]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
let mode = 'write';
let root = '.';
for (let i = 0; i < args.length; i += 1) {
  const a = args[i];
  if (a === '--write') mode = 'write';
  else if (a === '--check') mode = 'check';
  else if (a === '--root') {
    root = args[i + 1] ?? root;
    i += 1;
  } else if (!a.startsWith('--')) {
    root = a;
  } else {
    console.error(`unknown argument: ${a}`);
    process.exit(2);
  }
}
root = path.resolve(root);

const SEARCH_DIRS = [
  'cobol/src',
  'middleware/src',
  'middleware/services',
  'middleware/adapters',
  'middleware/core-client',
  'middleware/workers',
  'tests',
  'scripts',
];
const SEARCH_EXTS = new Set([
  '.cob',
  '.cpy',
  '.c',
  '.h',
  '.js',
  '.mjs',
  '.sh',
  '.sql',
  '.json',
  '.yaml',
  '.yml',
  '.py',
  '.txt',
  '.cases',
]);

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === 'node_modules' || e.name === '__pycache__') continue;
      walk(p, out);
    } else if ([...SEARCH_EXTS].some((x) => e.name.endsWith(x))) {
      out.push(p);
    }
  }
  return out;
}

function readSchemaTables() {
  const text = readFileSync(path.join(root, 'database', 'schema.sql'), 'utf8');
  const names = [];
  for (const m of text.matchAll(/^CREATE TABLE(?: IF NOT EXISTS)? `?([A-Za-z0-9_]+)`?/gm)) {
    if (!names.includes(m[1])) names.push(m[1]);
  }
  return names.sort();
}

export function build() {
  const files = SEARCH_DIRS.flatMap((d) => walk(path.join(root, d)));
  const blobs = new Map();
  for (const f of files) {
    try {
      blobs.set(f, readFileSync(f, 'utf8'));
    } catch {
      blobs.set(f, '');
    }
  }
  const tables = readSchemaTables();
  return tables.map((t) => {
    const re = new RegExp(`(?<![A-Za-z0-9_])${t}(?![A-Za-z0-9_])`);
    const hits = [...blobs.entries()].filter(([, b]) => re.test(b)).map(([f]) => path.relative(root, f));
    return {
      table: t,
      referenced: hits.length > 0,
      referencedIn: hits.slice(0, 8),
      audit: t.endsWith('_audit'),
      recommendation: hits.length > 0 ? 'KEEP' : 'DBA_REVIEW',
    };
  });
}

export function renderMarkdown(rows) {
  const unref = rows.filter((r) => !r.referenced);
  const lines = [
    '# Legacy Tables (report only — no DROP in this PR)',
    '',
    '> Generated by `scripts/report_legacy_tables.mjs --write`. Do not edit by hand.',
    '> DBA triages DBA_REVIEW rows to KEEP / DROP_CANDIDATE / DEFER with a',
    '> migration, backup/restore drill, and rollback plan. No table is dropped here.',
    '',
    `| Tables in schema.sql | ${rows.length} |`,
    `| Referenced in code/tests | ${rows.length - unref.length} |`,
    `| Unreferenced (DBA review) | ${unref.length} |`,
    '',
    '| Table | Referenced | Audit | Recommendation |',
    '| --- | --- | --- | --- |',
    ...rows.map(
      (r) => `| \`${r.table}\` | ${r.referenced ? 'yes' : 'no'} | ${r.audit ? 'yes' : 'no'} | ${r.recommendation} |`,
    ),
  ];
  return `${lines.join('\n')}\n`;
}

const rows = build();
const outPath = path.join(root, 'docs', 'LEGACY_TABLES.md');

if (mode === 'write') {
  writeFileSync(outPath, renderMarkdown(rows));
  console.log(
    `Wrote docs/LEGACY_TABLES.md (${rows.length} tables, ${rows.filter((r) => !r.referenced).length} unreferenced)`,
  );
} else {
  if (!existsSync(outPath)) {
    console.error('FAIL: docs/LEGACY_TABLES.md missing; run scripts/report_legacy_tables.mjs --write');
    process.exit(1);
  }
  const current = readFileSync(outPath, 'utf8');
  if (current !== renderMarkdown(rows)) {
    console.error('FAIL: docs/LEGACY_TABLES.md drifted; run scripts/report_legacy_tables.mjs --write after review');
    process.exit(1);
  }
  console.log(`OK: ${rows.length} tables`);
}
