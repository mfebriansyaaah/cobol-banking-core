// Documentation drift and link checker.
//
// - README generated stats must match scripts/docs_stats.mjs.
// - README generated test table must match scripts/build_test_table.mjs.
// - docs/COMPLEXITY_BASELINE.md must match scripts/audit_complexity.mjs.
// - docs/DATA_DICTIONARY.md must match scripts/generate_data_dictionary.mjs.
// - Opted-in long docs must have a fresh generated ToC (scripts/docs_toc.mjs).
// - Required community/runbook files must exist.
// - Local Markdown links must resolve. External links are intentionally not
//   gated (only first-party CI badge URLs exist; network checks would flake).
// - At least 80% of manifest modules must be referenced from handwritten
//   docs. Generated files ("> Generated by" header marker, e.g.
//   docs/MODULE_INDEX.md which lists every module by construction) are
//   excluded from the corpus so the gate stays meaningful.
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { collect, renderReadmeBlock, ROOT } from './docs_stats.mjs';
import { renderTestTable } from './build_test_table.mjs';
import { baselineRows, audit, parseBaselineMarkdown } from './audit_complexity.mjs';
import { generateDataDictionary } from './generate_data_dictionary.mjs';
import { tocStaleFiles } from './docs_toc.mjs';
import { findStaleClaims } from './ci/stale_claims.mjs';

const REQUIRED = [
  'README.md',
  'CONTRIBUTING.md',
  'SECURITY.md',
  'CHANGELOG.md',
  'docs/STATUS.md',
  'docs/MODULE_INDEX.md',
  'docs/COVERAGE.md',
  'docs/GOVERNANCE.md',
  'docs/runbooks/secret-rotation.md',
  '.github/pull_request_template.md',
  '.github/ISSUE_TEMPLATE/bug_report.md',
  '.github/ISSUE_TEMPLATE/feature_request.md',
];

const errors = [];

const walkMarkdown = (dir) => {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) out.push(...walkMarkdown(full));
    else if (entry.endsWith('.md')) out.push(full);
  }
  return out;
};

const stripCodeFences = (text) => text.replace(/```[\s\S]*?```/g, '');

const checkLinks = (file) => {
  const text = stripCodeFences(readFileSync(file, 'utf8'));
  const re = /\]\(([^)\s]+)\)/g;
  let m;
  while ((m = re.exec(text)) !== null) {
    const raw = m[1];
    if (/^(https?:|mailto:|#)/.test(raw)) continue;
    const target = raw.split('#')[0];
    if (!target) continue;
    const resolved = target.startsWith('/') ? path.join(ROOT, target) : path.resolve(path.dirname(file), target);
    if (!existsSync(resolved)) {
      errors.push(`${path.relative(ROOT, file)}: missing link target ${raw}`);
    }
  }
};

for (const rel of REQUIRED) {
  if (!existsSync(path.join(ROOT, rel))) errors.push(`missing required file: ${rel}`);
}

const stats = collect();
const readme = readFileSync(path.join(ROOT, 'README.md'), 'utf8');
const begin = '<!-- BEGIN GENERATED STATS -->';
const end = '<!-- END GENERATED STATS -->';
const start = readme.indexOf(begin);
const stop = readme.indexOf(end);
if (start < 0 || stop < start) {
  errors.push('README.md is missing the generated stats markers');
} else {
  const actual = readme.slice(start, stop + end.length);
  const expected = renderReadmeBlock(stats);
  if (actual !== expected) {
    errors.push('README generated stats are stale; run `node scripts/docs_stats.mjs --write`');
  }
}

for (const phrase of ['No hosted CI', 'All 11 roadmap items complete']) {
  if (readme.includes(phrase)) errors.push(`README.md still contains stale claim: "${phrase}"`);
}

{
  // Generated test table (maint-12a): rendered from tests/baseline_counts.txt.
  const begin = '<!-- BEGIN GENERATED TEST TABLE -->';
  const end = '<!-- END GENERATED TEST TABLE -->';
  const start = readme.indexOf(begin);
  const stop = readme.indexOf(end);
  if (start < 0 || stop < start) {
    errors.push('README.md is missing the generated test-table markers');
  } else {
    const actual = readme.slice(start, stop + end.length);
    const expected = renderTestTable(ROOT).trimEnd();
    if (actual.trimEnd() !== expected) {
      errors.push('README generated test table is stale; run `node scripts/build_test_table.mjs --write`');
    }
  }
}

{
  // Complexity baseline (maint-12a): docs/COMPLEXITY_BASELINE.md must match
  // a fresh audit (same comparison as `audit_complexity.mjs --check`).
  const docPath = path.join(ROOT, 'docs', 'COMPLEXITY_BASELINE.md');
  if (!existsSync(docPath)) {
    errors.push('docs/COMPLEXITY_BASELINE.md is missing; run `node scripts/audit_complexity.mjs --write`');
  } else {
    const recorded = parseBaselineMarkdown(readFileSync(docPath, 'utf8'));
    for (const [area, metric, value] of baselineRows(audit(ROOT))) {
      const key = `${area} | ${metric}`;
      if (!recorded.has(key)) errors.push(`COMPLEXITY_BASELINE.md is missing metric: ${key}`);
      else if (recorded.get(key) !== value) {
        errors.push(
          `COMPLEXITY_BASELINE.md is stale (${key}: recorded ${recorded.get(key)}, tree has ${value}); run \`node scripts/audit_complexity.mjs --write\` after review`,
        );
      }
    }
  }
}

{
  const p = path.join(ROOT, 'docs', 'CODE_CANDIDATES.md');
  const manifestPath = path.join(ROOT, 'manifest', 'code_candidates.json');
  if (existsSync(p) && existsSync(manifestPath)) {
    const rows = [...readFileSync(p, 'utf8').matchAll(/^\| `([^`]+)` \|/gm)].map((m) => m[1]);
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')).candidates.map((c) => c.module);
    for (const module of rows) {
      if (!manifest.includes(module)) errors.push(`CODE_CANDIDATES.md stale row: ${module} not in manifest`);
      if (!existsSync(path.join(ROOT, 'cobol', 'src', `${module}.cob`))) {
        errors.push(`CODE_CANDIDATES.md stale module: ${module} has no source`);
      }
    }
  }
}

{
  // Data dictionary (docs hygiene): generated from database/schema.sql so
  // the table/column inventory cannot drift from the baseline schema.
  const p = path.join(ROOT, 'docs', 'DATA_DICTIONARY.md');
  if (!existsSync(p)) {
    errors.push('docs/DATA_DICTIONARY.md is missing; run `node scripts/generate_data_dictionary.mjs --write`');
  } else if (readFileSync(p, 'utf8') !== generateDataDictionary(ROOT)) {
    errors.push(
      'docs/DATA_DICTIONARY.md is stale vs database/schema.sql; run `node scripts/generate_data_dictionary.mjs --write`',
    );
  }
}

const markdownFiles = [
  path.join(ROOT, 'README.md'),
  path.join(ROOT, 'CONTRIBUTING.md'),
  path.join(ROOT, 'SECURITY.md'),
  path.join(ROOT, 'CHANGELOG.md'),
  ...walkMarkdown(path.join(ROOT, 'docs')),
].filter((f) => existsSync(f));
markdownFiles.forEach(checkLinks);

// Stale volatile numbers and wrong required-check names (CI-006). Historical
// R0 evidence lines containing "historical" are skipped by the scanner.
// tests/README.md carries fleet counts too, so it is scanned here even
// though link/reach checks stay on markdownFiles.
const staleExtra = [path.join(ROOT, 'tests', 'README.md')].filter((f) => existsSync(f));
const staleFiles = [...markdownFiles, ...staleExtra].map((f) => ({
  path: path.relative(ROOT, f),
  text: readFileSync(f, 'utf8'),
}));
for (const hit of findStaleClaims(staleFiles)) {
  errors.push(`${hit.path}:${hit.line}: stale claim (${hit.rule}): ${hit.message}`);
}

const allDocs = markdownFiles
  .filter((f) => {
    // Generated files list every module by construction; counting them
    // would pin reach at 100% and make the gate vacuous.
    try {
      return !readFileSync(f, 'utf8')
        .split('\n', 12)
        .some((l) => l.includes('Generated by'));
    } catch {
      return true;
    }
  })
  .map((f) => readFileSync(f, 'utf8'))
  .join('\n');
const reach = stats.modules.filter((m) => allDocs.includes(m.module)).length;
const reachPct = stats.modules.length ? (100 * reach) / stats.modules.length : 0;
if (reachPct < 80) {
  const missing = stats.modules.map((m) => m.module).filter((mod) => !allDocs.includes(mod));
  errors.push(
    `handwritten documentation reach is ${reachPct.toFixed(1)}% (need >=80%); unreferenced: ${missing.join(', ')}`,
  );
}

{
  // Table of contents freshness for opted-in long docs (docs hygiene).
  for (const f of tocStaleFiles(ROOT)) {
    errors.push(`${f} has a stale generated ToC; run \`node scripts/docs_toc.mjs --write\``);
  }
}

{
  // Docs index coverage: every living doc must be linked from its index so
  // it stays discoverable. Archive docs are covered by their own index.
  const indexRoots = [
    { dir: 'docs', index: path.join(ROOT, 'docs', 'README.md') },
    { dir: 'docs/runbooks', index: path.join(ROOT, 'docs', 'runbooks', 'README.md') },
    { dir: 'docs/adr', index: path.join(ROOT, 'docs', 'adr', 'README.md') },
    { dir: 'docs/archive', index: path.join(ROOT, 'docs', 'archive', 'README.md') },
  ];
  for (const { dir, index } of indexRoots) {
    if (!existsSync(index)) {
      errors.push(`${path.relative(ROOT, index)} is missing; every docs section needs an index`);
      continue;
    }
    const indexText = readFileSync(index, 'utf8');
    const linked = new Set([...indexText.matchAll(/\]\(([^)\s]+)\)/g)].map((m) => m[1].split('#')[0]));
    for (const f of readdirSync(path.join(ROOT, dir)).filter((x) => x.endsWith('.md') && x !== 'README.md')) {
      const rel = f;
      const abs = path.join(ROOT, dir, f);
      const hit = [...linked].some((l) => l === rel || l === `./${rel}` || l.endsWith(`/${rel}`) || abs.endsWith(l));
      if (!hit) errors.push(`${dir}/${f} is not linked from its index; add it to ${path.relative(ROOT, index)}`);
    }
  }
}

if (errors.length) {
  console.error('DOCUMENTATION CHECK FAILED:');
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}

console.log(
  `OK: docs stats current; ${markdownFiles.length} markdown file(s); links valid; handwritten module reach ${reach}/${stats.modules.length} (${reachPct.toFixed(1)}%)`,
);
